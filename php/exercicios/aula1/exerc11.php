<?php
    $contador = 5;
    echo $contador++; // retorna o valor ANTES incrementar, retorna 5 e resulta em 6.
    echo ++$contador; // retorna o valor APÓS incrementar, retorna 7.
    echo $contador--; // retorna o valor ANTES de decrementar, retorna 7 e resulta em 6.
    echo --$contador; // retorna o valor APÓS decrementar, retorna 5.
?>